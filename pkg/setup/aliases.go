package setup

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nimblescape/nimble/pkg/config"
	"github.com/nimblescape/nimble/pkg/nimble"
)

// AliasesFile is the generated shell file the managed ~/.zshrc and ~/.bashrc load last, in
// interactive shells: the nimble function, the directory aliases (personal/aliases.yaml:
// <name> alone runs cd <dir>) and an alias per host of the generated ssh config (<host>
// alone runs ssh <host>).
const AliasesFile = "aliases.sh"

// NextEnv names the file the nimble function hands nimble: shell lines (an alias added or
// removed) it runs in the calling shell once nimble is done, so the change works at once.
const NextEnv = "NIMBLE_NEXT"

// WriteAliases keeps the alias file in step with personal/aliases.yaml and the generated ssh
// config. A machine without either still gets it, for the nimble function.
func WriteAliases() error {
	dirs, err := config.DirAliases()
	if err != nil {
		return err
	}
	file := nimble.CacheDir(AliasesFile)
	want := aliasesScript(dirs, nimble.ReadTrim(nimble.CacheDir("ssh_config")))
	if nimble.ReadTrim(file) == strings.TrimSpace(want) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		return err
	}
	return os.WriteFile(file, []byte(want), 0o644)
}

// DirAliasLine is the alias for a directory alias, as the alias file has it.
func DirAliasLine(name, dir string) string {
	if rel, ok := strings.CutPrefix(dir, "~/"); ok {
		dir = "$HOME/" + rel
	} else if dir == "~" {
		dir = "$HOME"
	}
	return fmt.Sprintf(`alias %s='cd "%s"'`, name, dir)
}

// aliasesScript is the alias file. Directory aliases come after your shell files and win:
// you made them with nimble alias add. A host's alias steps back for a name that means
// something already — a command, an alias (a directory alias too) or a function.
func aliasesScript(dirs map[string]string, sshConfig string) string {
	var b strings.Builder
	b.WriteString(`# Generated by nimble — don't edit. ~/.zshrc and ~/.bashrc load it last, in interactive shells:
#   <name> alone runs cd <dir>    nimble alias add|remove|list (personal/aliases.yaml)
#   <host> alone runs ssh <host>  every host in ~/.nimble/cache/ssh_config, unless the name
#                                 means something already; NIMBLE_NO_SSH_ALIASES=1 turns them off
case $- in *i*) ;; *) return 0 ;; esac

# nimble, with what it changes in this shell (an alias added or removed) taking effect at once
nimble() {
  local next rc
  next="${TMPDIR:-/tmp}/nimble-next.$$"
  ` + NextEnv + `="$next" command nimble "$@"
  rc=$?
  if [ -f "$next" ]; then . "$next"; rm -f "$next"; fi
  return $rc
}
`)
	names := make([]string, 0, len(dirs))
	for n := range dirs {
		names = append(names, n)
	}
	sort.Strings(names)
	if len(names) > 0 {
		b.WriteString("\n# directories\n")
	}
	for _, n := range names {
		if config.CheckAlias(n, dirs[n]) == nil {
			b.WriteString(DirAliasLine(n, dirs[n]) + "\n")
		}
	}
	var hosts []string
	for _, l := range strings.Split(sshConfig, "\n") {
		if name, ok := strings.CutPrefix(l, "Host "); ok && !strings.ContainsAny(name, "*?! \t'\"$`\\/=") {
			hosts = append(hosts, name)
		}
	}
	if len(hosts) > 0 {
		b.WriteString("\n# hosts\nif [ -z \"${NIMBLE_NO_SSH_ALIASES:-}\" ]; then\n")
		for _, h := range hosts {
			fmt.Fprintf(&b, "  command -v %[1]s >/dev/null 2>&1 || alias %[1]s='ssh %[1]s'\n", h)
		}
		b.WriteString("fi\n")
	}
	return b.String()
}
