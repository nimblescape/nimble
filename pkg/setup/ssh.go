// SSHClient gives this workstation the ssh that works with both of nimble's hardware keys,
// the daily key in the Secure Enclave and the YubiKey backups, ykman (a YubiKey's FIDO
// PIN, which one is plugged in) and the tools of libfido2 (the sealing key of a YubiKey,
// nimble token key yubikey). macOS's own OpenSSH has no FIDO support, so a Mac gets
// Homebrew's, linked: Homebrew's bin comes first in PATH, so it is the ssh of every shell
// and of nimble. It reaches the Secure Enclave through macOS's provider
// (/usr/lib/ssh-keychain.dylib) as the system's does. Debian's openssh-client talks to FIDO
// keys itself. upgrade also brings them up to date (nimble update).
func SSHClient(upgrade bool) error {
	if !Darwin() {
		if _, err := nimble.AptInstall("openssh-client", "yubikey-manager", "fido2-tools"); err != nil {
			return err
		}
		if upgrade {
			return aptUpgrade("yubikey-manager")
		}
		return nil
	}
	for _, formula := range []string{"openssh", "ykman", "libfido2"} {
		if err := brew(formula, false); err != nil {
			return err
		}
		if upgrade {
			if err := brewUpgrade(formula, false); err != nil {
				return err
			}
		}
	}
	if _, _, ok := keys.FIDOSSH(); ok {
		return nil
	}
	nimble.Say("brew link openssh (Homebrew's ssh becomes the ssh in PATH)")
	if err := (nimble.Cmd{Name: "brew", Args: []string{"link", "openssh"}, Quiet: true}).Do(); err != nil {
		return err
	}
	if ssh, _, ok := keys.FIDOSSH(); !ok {
		return errors.New("ssh is still " + ssh + " — Homebrew's bin (" + nimble.BrewPrefix() + "/bin) must come before /usr/bin in PATH")
	}
	return nil
}

// SSHConfig generates the workstation's ssh client config for all hosts
// (~/.nimble/cache/ssh_config, from hosts/ + ssh/defaults) and makes ~/.ssh/config include
// it. It stays on the workstation: a host gets only its own (HostSSHConfig).
func SSHConfig(c *config.Config) error {
	defaults, err := os.ReadFile(nimble.RepoFile("ssh", "defaults"))
	if err != nil {
		return err
	}
	return installSSHConfig("# Generated by nimble from ~/.nimble/hosts/ and ~/.nimble/ssh/defaults — don't edit.\n"+
		"# Host entries come first: for each option ssh uses the first value it finds.\n\n"+
		"# macOS's own ssh knows UseKeychain, the OpenSSH nimble sets up doesn't: lines with it\n"+
		"# (in ~/.ssh/config, after the Include) mustn't stop it.\n"+
		"IgnoreUnknown UseKeychain\n\n"+
		hosts.SSHConfig(c, keys.HandlePath)+string(defaults), "ssh config for the hosts")
}

// HostSSHConfig gives a host the ssh entries its reach names: the workstation rendered them
// into the snapshot (hosts.SnapshotSSHConfig); they go to ~/.nimble/cache/ssh_config, which
// ~/.ssh/config includes. Without (reach removed), what nimble wrote is taken out again.
func HostSSHConfig() error {
	if !nimble.IsSnapshot() {
		return nil
	}
	if body, err := os.ReadFile(nimble.RepoFile(hosts.SnapshotSSHConfig)); err == nil {
		return installSSHConfig(string(body), "ssh config for the hosts this one reaches")
	}
	gen := nimble.CacheDir("ssh_config")
	if !nimble.Exists(gen) {
		return nil
	}
	if err := os.Remove(gen); err != nil {
		return err
	}
	if err := WriteAliases(); err != nil { // the hosts' aliases go with it
		return err
	}
	cfg := filepath.Join(nimble.Home(), ".ssh", "config")
	cur, err := os.ReadFile(cfg)
	if err != nil {
		return nil
	}
	rest := strings.TrimLeft(strings.Join(withoutInclude(string(cur)), "\n"), "\n")
	if strings.TrimSpace(rest) == "" {
		err = os.Remove(cfg)
	} else {
		err = os.WriteFile(cfg, []byte(rest), 0o600)
	}
	if err == nil {
		nimble.Say("removed the ssh config for other hosts (no reach in the host file)")
	}
	return err
}

// withoutInclude is ~/.ssh/config's lines without the Include of a generated ssh_config.
func withoutInclude(cur string) []string {
	var kept []string
	for _, l := range strings.Split(cur, "\n") {
		if !(strings.HasPrefix(l, "Include ") && strings.HasSuffix(l, "/cache/ssh_config")) {
			kept = append(kept, l)
		}
	}
	return kept
}

// installSSHConfig writes the generated ssh config (what says what changed) and makes
// ~/.ssh/config include it, at its top: ssh uses the first value it finds.
func installSSHConfig(want, what string) error {
	gen := nimble.CacheDir("ssh_config")
	if nimble.ReadTrim(gen) != strings.TrimSpace(want) {
		if err := os.MkdirAll(filepath.Dir(gen), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(gen, []byte(want), 0o644); err != nil {
			return err
		}
		nimble.Say(what + " → " + nimble.Tilde(gen))
	}
	if err := WriteAliases(); err != nil { // an alias per host
		return err
	}

	cfg := filepath.Join(nimble.Home(), ".ssh", "config")
	include := "Include " + nimble.Tilde(gen)
	cur, _ := os.ReadFile(cfg)
	if strings.Contains(string(cur), include) {
		return nil
	}
	// a previous location of the generated file (e.g. before the repo moved): replace it
	kept := withoutInclude(string(cur))
	if len(cur) > 0 {
		bak := filepath.Join(nimble.BackupDir(), ".ssh", "config")
		if err := os.MkdirAll(filepath.Dir(bak), 0o700); err != nil {
			return err
		}
		if err := os.WriteFile(bak, cur, 0o600); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(filepath.Dir(cfg), 0o700); err != nil {
		return err
	}
	body := include + "\n"
	if rest := strings.TrimLeft(strings.Join(kept, "\n"), "\n"); rest != "" {
		body += "\n" + rest
	}
	if err := os.WriteFile(cfg, []byte(body), 0o600); err != nil {
		return err
	}
	nimble.Say("~/.ssh/config: " + include)
	return nil
}
