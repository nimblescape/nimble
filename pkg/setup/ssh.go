// SSHClient gives this workstation the ssh that works with both of nimble's hardware keys,
// the daily key in the Secure Enclave and the YubiKey backups, and ykman (a YubiKey's FIDO
// PIN, which one is plugged in). macOS's own OpenSSH has no FIDO support, so a Mac gets
// Homebrew's, linked: Homebrew's bin comes first in PATH, so it is the ssh of every shell
// and of nimble. It reaches the Secure Enclave through macOS's provider
// (/usr/lib/ssh-keychain.dylib) as the system's does. Debian's openssh-client talks to FIDO
// keys itself. upgrade also brings them up to date (nimble update).
func SSHClient(upgrade bool) error {
	if !Darwin() {
		if _, err := nimble.AptInstall("openssh-client", "yubikey-manager"); err != nil {
			return err
		}
		if upgrade {
			return aptUpgrade("yubikey-manager")
		}
		return nil
	}
	for _, formula := range []string{"openssh", "ykman"} {
		if err := brew(formula, false); err != nil {
			return err
		}
		if upgrade {
			if err := brewUpgrade(formula, false); err != nil {
				return err
			}
		}
	}
	if _, _, ok := keys.FIDOSSH(); ok {
		return nil
	}
	nimble.Say("brew link openssh (Homebrew's ssh becomes the ssh in PATH)")
	if err := (nimble.Cmd{Name: "brew", Args: []string{"link", "openssh"}, Quiet: true}).Do(); err != nil {
		return err
	}
	if ssh, _, ok := keys.FIDOSSH(); !ok {
		return errors.New("ssh is still " + ssh + " — Homebrew's bin (" + nimble.BrewPrefix() + "/bin) must come before /usr/bin in PATH")
	}
	return nil
}

// SSHConfig generates the workstation's ssh client config for all hosts
// (~/.nimble/cache/ssh_config, from hosts/ + ssh/defaults) and makes ~/.ssh/config include
// it. The hosts' own ssh config is never touched.
func SSHConfig(c *config.Config) error {
	defaults, err := os.ReadFile(nimble.RepoFile("ssh", "defaults"))
	if err != nil {
		return err
	}
	gen := nimble.CacheDir("ssh_config")
	want := "# Generated by nimble from ~/.nimble/hosts/ and ~/.nimble/ssh/defaults — don't edit.\n" +
		"# Host entries come first: for each option ssh uses the first value it finds.\n\n" +
		"# macOS's own ssh knows UseKeychain, the OpenSSH nimble sets up doesn't: lines with it\n" +
		"# (in ~/.ssh/config, after the Include) mustn't stop it.\n" +
		"IgnoreUnknown UseKeychain\n\n" +
		hosts.SSHConfig(c, keys.HandlePath) + string(defaults)
	if nimble.ReadTrim(gen) != strings.TrimSpace(want) {
		if err := os.MkdirAll(filepath.Dir(gen), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(gen, []byte(want), 0o644); err != nil {
			return err
		}
		nimble.Say("ssh config for the hosts → " + nimble.Tilde(gen))
	}

	cfg := filepath.Join(nimble.Home(), ".ssh", "config")
	include := "Include " + nimble.Tilde(gen)
	cur, _ := os.ReadFile(cfg)
	if strings.Contains(string(cur), include) {
		return nil
	}
	// a previous location of the generated file (e.g. before the repo moved): replace it
	lines := strings.Split(string(cur), "\n")
	kept := lines[:0]
	for _, l := range lines {
		if !(strings.HasPrefix(l, "Include ") && strings.HasSuffix(l, "/cache/ssh_config")) {
			kept = append(kept, l)
		}
	}
	if len(cur) > 0 {
		bak := filepath.Join(nimble.BackupDir(), ".ssh", "config")
		if err := os.MkdirAll(filepath.Dir(bak), 0o700); err != nil {
			return err
		}
		if err := os.WriteFile(bak, cur, 0o600); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(filepath.Dir(cfg), 0o700); err != nil {
		return err
	}
	body := include + "\n"
	if rest := strings.TrimLeft(strings.Join(kept, "\n"), "\n"); rest != "" {
		body += "\n" + rest
	}
	if err := os.WriteFile(cfg, []byte(body), 0o600); err != nil {
		return err
	}
	nimble.Say("~/.ssh/config: " + include)
	return nil
}
